def test_make_transport_selects_component_mode(monkeypatch):
    from relay import main

    seen = {}

    class FakeComponent:
        def __init__(self, cfg):
            seen["cfg"] = cfg

    monkeypatch.setattr(main, "ComponentTransport", FakeComponent)
    cfg = component_config()
    assert isinstance(main.make_transport(cfg), FakeComponent)
    assert seen["cfg"] is cfg


def test_run_service_uses_component_routing_end_to_end(monkeypatch):
    from relay import main

    async def scenario():
        mock = MockUpstream()
        async with serve(mock) as url:
            cfg = component_config(api_url=url)
            transport = FakeComponentTransport()
            monkeypatch.setattr(main, "make_transport", lambda _cfg: transport)
            stop = asyncio.Event()
            service = asyncio.create_task(main.run_service(cfg, stop=stop))
            try:
                await wait_until(lambda: transport.started)
                await wait_until(lambda: mock.stream_connections >= 1)
                await mock.push(message_event(guid="component-1", sender=PEER))
                await wait_until(lambda: len(transport.sent) == 1)
                assert transport.sent[0]["frm"] == PEER_JID
                assert transport.sent[0]["to"] == OWNER
                stop.set()
                await asyncio.wait_for(service, timeout=5)
                assert transport.stopped
            finally:
                if not service.done():
                    service.cancel()
                    await asyncio.gather(service, return_exceptions=True)

    run(scenario())
