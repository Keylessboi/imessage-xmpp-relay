"""Component mode (XEP-0114): JID mapping, config, transport and routing.

No network and no XMPP server: slixmpp's ComponentXMPP is replaced by
tests/fakes.py::FakeComponentXmpp and the routing layer sees a fake
component transport, exactly like tests/fakes.py::FakeTransport does for
client mode.
"""
from __future__ import annotations

import asyncio
import logging

import pytest

from conftest import message_event, run, wait_until
from fakes import (
    FakeComponentTransport,
    FakeComponentXmpp,
    FakeStanza,
)
from mock_upstream import MockUpstream, serve

from relay.component import (
    ComponentTransport,
    handle_to_localpart,
    is_phone_handle,
    jid_to_handle,
    localpart_to_handle,
    peer_jid,
)
from relay.config import Config, ConfigError
from relay.core import Bridge
from relay.models import IncomingXmpp
from relay.upstream import UpstreamClient

DOMAIN = "imessage.example.org"
OWNER = "you@example.org"
PEER = "+15557654321"
PEER_JID = PEER + "@" + DOMAIN
SECRET = "component-shared-secret"


def component_config(**overrides) -> Config:
    defaults = dict(
        mode="component",
        component_jid=DOMAIN,
        component_domain=DOMAIN,
        component_host="127.0.0.1",
        component_port=5347,
        component_secret=SECRET,
        component_owner=OWNER,
        targets=(OWNER,),
        allowed=frozenset({OWNER}),
    )
    defaults.update(overrides)
    return Config(**defaults)


def component_env(**overrides) -> dict:
    env = {
        "XMPP_MODE": "component",
        "COMPONENT_JID": DOMAIN,
        "COMPONENT_SECRET": SECRET,
        "COMPONENT_OWNER": OWNER,
    }
    env.update(overrides)
    return env


def stanza(*, body="", sender=OWNER, to=PEER_JID, mtype="chat") -> FakeStanza:
    return FakeStanza(type=mtype, body=body, to=to, **{"from": sender})


def component_transport(**overrides):
    fake = FakeComponentXmpp()
    cfg = component_config(**overrides)
    return ComponentTransport(cfg, xmpp=fake), fake, cfg


def wire_bridge(cfg, url=None):
    transport = FakeComponentTransport()
    upstream = UpstreamClient(url or cfg.api_url)
    return Bridge(cfg, transport, upstream), transport, upstream


# -- handle <-> JID mapping ------------------------------------------------


def test_phone_handles_become_their_own_plus_jid():
    assert is_phone_handle("+1 (555) 765-4321")
    assert handle_to_localpart("+1 (555) 765-4321") == PEER
    assert peer_jid("+15557654321", DOMAIN) == PEER_JID
    assert jid_to_handle(PEER_JID, DOMAIN) == PEER
    assert jid_to_handle(PEER_JID + "/phone", DOMAIN) == PEER


def test_apple_id_handle_gets_a_sanitised_reversible_localpart():
    jid = peer_jid("John.Doe@iCloud.com", DOMAIN)
    assert jid == "john.doe-40icloud.com@" + DOMAIN
    assert localpart_to_handle("john.doe-40icloud.com") == "john.doe@icloud.com"
    assert jid_to_handle(jid, DOMAIN) == "john.doe@icloud.com"


def test_odd_identifiers_round_trip_instead_of_being_dropped():
    for handle in ("relay:1234/abc", "urn:biz:bizarre", "a-b@example.org", "x y"):
        jid = peer_jid(handle, DOMAIN)
        assert jid is not None, handle
        assert jid_to_handle(jid, DOMAIN) == handle, handle


def test_non_peer_jids_are_rejected():
    assert jid_to_handle("", DOMAIN) is None
    assert jid_to_handle("+15557654321", DOMAIN) is None
    assert jid_to_handle("+15557654321@other.example", DOMAIN) is None
    assert jid_to_handle("alice@" + DOMAIN, DOMAIN) is None  # not generated by us
    assert jid_to_handle("bad local@" + DOMAIN, DOMAIN) is None
    assert jid_to_handle("-zz@" + DOMAIN, DOMAIN) is None
    assert peer_jid("", DOMAIN) is None
    assert peer_jid(PEER, "") is None


def test_generated_jids_are_valid_slixmpp_jids():
    slixmpp = pytest.importorskip("slixmpp")
    for handle in (PEER, "John.Doe@iCloud.com", "relay:1234/abc", "x y"):
        jid = peer_jid(handle, DOMAIN)
        assert str(slixmpp.JID(jid)) == jid, handle


