def test_start_connects_to_the_component_listener_and_stops_cleanly():
    async def scenario():
        transport, fake, cfg = component_transport()
        task = asyncio.create_task(transport.start())
        await wait_until(lambda: bool(fake.connected))
        assert fake.connected == [(cfg.component_host, cfg.component_port)]
        await fake.fire("session_start", FakeStanza())
        await asyncio.sleep(0)
        await transport.stop()
        await asyncio.wait_for(task, timeout=2)
        assert fake.disconnect_calls == 1

    run(scenario())


def test_a_rejected_handshake_is_retried_without_waiting_forever():
    async def scenario():
        transport, fake, _ = component_transport(
            backoff_initial=0.01, backoff_max=0.02, backoff_jitter=0.0
        )
        task = asyncio.create_task(transport.start())
        await wait_until(lambda: len(fake.connected) == 1)
        # XEP-0114 handshake failed (bad secret): the stream closes before
        # session_start. The transport must retry instead of hanging.
        await fake.fire("disconnected", FakeStanza())
        await wait_until(lambda: len(fake.connected) >= 2, timeout=2)
        await transport.stop()
        await asyncio.wait_for(task, timeout=2)

    run(scenario())


